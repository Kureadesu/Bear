import 'package:cloud_firestore/cloud_firestore.dart';
import 'package:firebase_auth/firebase_auth.dart';

class PairingService {
  final _db = FirebaseFirestore.instance;

  String get _uid {
    final user = FirebaseAuth.instance.currentUser;

    if (user == null) {
      throw StateError('Please sign in first.');
    }

    return user.uid;
  }

  Future<String> createInvite() async {
    final uid = _uid;

    // Firestore generates a long, random document ID.
    // The couple and its invite use the same ID.
    final coupleRef = _db.collection('couples').doc();
    final inviteRef = _db.collection('invites').doc(coupleRef.id);
    final profileRef = _db.collection('users').doc(uid);

    await _db.runTransaction((transaction) async {
      final profile = await transaction.get(profileRef);

      if (!profile.exists) {
        throw StateError('Your profile is missing. Sign out and back in.');
      }

      if (profile.data()?['coupleId'] != null) {
        throw StateError('You already have a shared space.');
      }

      transaction.set(coupleRef, {
        'memberIds': [uid],
        'createdAt': FieldValue.serverTimestamp(),
      });

      transaction.set(inviteRef, {
        'ownerId': uid,
        'status': 'open',
        'acceptedBy': null,
        'createdAt': FieldValue.serverTimestamp(),
        'expiresAt': Timestamp.fromDate(
          DateTime.now().add(const Duration(hours: 23)),
        ),
      });

      transaction.update(profileRef, {'coupleId': coupleRef.id});
    });

    return coupleRef.id;
  }

  Future<void> acceptInvite(String rawCode) async {
    final code = rawCode.trim();

    // Codes generated by Firestore contain 20 letters/numbers.
    if (!RegExp(r'^[A-Za-z0-9]{20}$').hasMatch(code)) {
      throw StateError('Please enter the complete invite code.');
    }

    final uid = _uid;
    final profileRef = _db.collection('users').doc(uid);
    final inviteRef = _db.collection('invites').doc(code);
    final coupleRef = _db.collection('couples').doc(code);

    await _db.runTransaction((transaction) async {
      // All reads happen before writes.
      final profile = await transaction.get(profileRef);
      final invite = await transaction.get(inviteRef);

      if (!profile.exists) {
        throw StateError('Your profile is missing. Sign out and back in.');
      }

      if (profile.data()?['coupleId'] != null) {
        throw StateError('You already have a shared space.');
      }

      final inviteData = invite.data();

      if (inviteData == null) {
        throw StateError('That invitation was not found.');
      }

      if (inviteData['ownerId'] == uid) {
        throw StateError('You cannot accept your own invitation.');
      }

      if (inviteData['status'] != 'open') {
        throw StateError('That invitation has already been used.');
      }

      final expiresAt = inviteData['expiresAt'];

      if (expiresAt is! Timestamp ||
          !expiresAt.toDate().isAfter(DateTime.now())) {
        throw StateError('That invitation has expired.');
      }

      final couple = await transaction.get(coupleRef);
      final members = couple.data()?['memberIds'];
      final ownerId = inviteData['ownerId'];

      if (members is! List || members.length != 1 || members.first != ownerId) {
        throw StateError('That shared space is no longer available.');
      }

      transaction.update(coupleRef, {
        'memberIds': [ownerId, uid],
      });

      transaction.update(inviteRef, {'status': 'accepted', 'acceptedBy': uid});

      transaction.update(profileRef, {'coupleId': code});
    });
  }
}
